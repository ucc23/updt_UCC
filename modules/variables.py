# Used by: B
# Coefficients to transform fundamental parameters
#
# Z to FeH
c_z_sun = 0.0152

# Coefficients to transform from E(V-I) & E(J-H) and Gaia's bands are taken from
# Wang & Chen (2019), Table 3:
# https://iopscience.iop.org/article/10.3847/1538-4357/ab1c61
#
# Av = 1/(c_x - c_Y) * E(X-Y)
coeffs = {
    "c_B": 1.317,  # Johnson B
    "c_V": 1.0,  # Johnson V
    "c_I": 0.63,  # SDSS I
    "c_G": 0.789,  # Gaia G
    "c_BP": 1.002,  # Gaia BP
    "c_RP": 0.589,  # Gaia RP
    "c_J": 0.243,  # 2MASS J
    "c_H": 0.131,  # 2MASS H
    "c_K": 0.078,  # 2MASS Ks
}
c_Ebv = 1 / (coeffs["c_B"] - coeffs["c_V"])
c_Evi = 1 / (coeffs["c_V"] - coeffs["c_I"])
c_Ag = 1 / coeffs["c_G"]
c_Ah = 1 / coeffs["c_H"]
c_Ak = 1 / coeffs["c_K"]
c_Ebprp = 1 / (coeffs["c_BP"] - coeffs["c_RP"])
c_Egrp = 1 / (coeffs["c_G"] - coeffs["c_RP"])
c_Ejh = 1 / (coeffs["c_J"] - coeffs["c_H"])

# Used by: A (to check that every format in 'pars_formats' has a converter), B
# Converters from each parameter format (see 'pars_formats') to the UCC units:
# Av [mag], dist [kpc], age [Myr], met [Fe/H], mass [Msun]. Each returns the
# value as a formatted string
fmt_to_UCC = {
    "loga": lambda x: f"{10**x / 1e6:.0f}",
    "amyr": lambda x: f"{x:.0f}",
    "agyr": lambda x: f"{1000 * x:.0f}",
    "feh": lambda x: f"{x:.3f}",
    "z": lambda x: f"{np.log10(x / c_z_sun):.3f}",
    "mass": lambda x: f"{x:.0f}",
    "logm": lambda x: f"{10**x:.0f}",
    "bf": lambda x: f"{x:.2f}",
    "bs_f": lambda x: f"{x:.2f}",
    "bs_n": lambda x: f"{x:.0f}",
    "av": lambda x: f"{x:.2f}",
    "ag": lambda x: f"{c_Ag * x:.2f}",
    "ah": lambda x: f"{c_Ah * x:.2f}",
    "ak": lambda x: f"{c_Ak * x:.2f}",
    "ebv": lambda x: f"{c_Ebv * x:.2f}",
    "evi": lambda x: f"{c_Evi * x:.2f}",
    "ejh": lambda x: f"{c_Ejh * x:.2f}",
    "ebprp": lambda x: f"{c_Ebprp * x:.2f}",
    "egrp": lambda x: f"{c_Egrp * x:.2f}",
    "dav": lambda x: f"{x:.2f}",
    "dkpc": lambda x: f"{x:.2f}",
    "dpc": lambda x: f"{x / 1000:.2f}",
    "dm": lambda x: f"{10 ** (0.2 * (x + 5)) / 1000:.2f}",
}

